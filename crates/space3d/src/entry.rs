//! Platform entry points used by [`crate::main!`].
//!
//! You normally don't call these directly: write a `build` function that configures the
//! [`App`] and let `space3d::main!(build)` generate the right entry point for every target.

use space3d_core::App;

/// Create an [`App`], let `build` configure it, then hand it to its runner (`App::run`).
///
/// On desktop this blocks until the game exits; on the web it returns immediately and the
/// browser drives the frame loop.
pub fn run(build: impl FnOnce(&mut App)) {
    let mut app = App::new();
    build(&mut app);
    app.run();
}

/// The body of the generated `pub fn main()`.
///
/// * desktop and iOS (a bundled Rust binary): [`run`] the app;
/// * web: nothing — the generated `#[wasm_bindgen(start)]` function runs the app instead
///   (so it also works when wasm-bindgen treats `main` as the start function);
/// * Android: nothing — the OS calls the generated `android_main`.
pub fn main_entry(build: impl FnOnce(&mut App)) {
    #[cfg(not(any(target_arch = "wasm32", target_os = "android")))]
    run(build);
    #[cfg(any(target_arch = "wasm32", target_os = "android"))]
    {
        let _ = build;
    }
}

/// Web start: route panics to `console.error`, then [`run`]. Logging to the browser console is
/// set up by [`crate::LogPlugin`] (or `UiPlugin`, which adds its profiler/console layers) when
/// `build` adds [`crate::DefaultPlugins`].
#[cfg(target_arch = "wasm32")]
pub fn run_web(build: impl FnOnce(&mut App)) {
    console_error_panic_hook::set_once();
    run(build);
}

/// Android start (NativeActivity): stash the `AndroidApp` for the winit event loop, build and
/// run the app. See `space3d_platform::mobile`.
#[cfg(all(target_os = "android", feature = "platform"))]
pub fn run_android(android_app: space3d_platform::AndroidApp, build: impl FnOnce(&mut App)) {
    // The APK's assets are read through the activity's asset manager (`AndroidAssetSource`).
    #[cfg(feature = "assets")]
    space3d_assets::set_android_asset_manager(android_app.asset_manager());
    space3d_platform::android_main_entry(android_app, build);
}

/// iOS start, called from the Xcode project's `main.m` via the generated `start_app()`.
/// Never returns (UIKit owns the main thread).
#[cfg(target_os = "ios")]
pub fn run_ios(build: impl FnOnce(&mut App)) {
    run(build);
}

/// Generate the entry point(s) for every platform from one `build` function.
///
/// `build` is anything callable as `FnOnce(&mut App)` — usually a function path. The macro
/// expands to:
///
/// | target | generated item | what runs |
/// |---|---|---|
/// | desktop (Windows, macOS, Linux) | `pub fn main()` | `App::new()` → `build(&mut app)` → `app.run()` |
/// | web (`wasm32`) | `#[wasm_bindgen(start)] pub fn __space3d_wasm_start()` (+ a no-op `main`) | panic hook (`console.error`), then the same as desktop (`DefaultPlugins` logs to the browser console); `run()` returns and the browser drives frames |
/// | Android | `#[no_mangle] fn android_main(AndroidApp)` | `space3d_platform::android_main_entry` (NativeActivity, e.g. via `cargo apk`) |
/// | iOS | `#[no_mangle] pub extern "C" fn start_app()` (+ `main` also runs the app) | call `start_app()` from the Xcode project's `main.m`; never returns |
///
/// Use it **once per final artifact**:
///
/// * **Desktop + web**: put it in the binary, `src/main.rs`.
/// * **Android/iOS**: those platforms load a *library* (`cdylib` for `cargo apk`, `staticlib`
///   for Xcode). Keep the game in a library crate and invoke the macro once more in a small
///   crate with `crate-type = ["cdylib", "staticlib"]` — the layout `space3d new` generates
///   (`src/main.rs` + `mobile/src/lib.rs`, both `space3d::main!(my_game::build);`), so desktop
///   and web builds never link the mobile library types.
///
/// ```no_run
/// use space3d::prelude::*;
///
/// fn build(app: &mut App) {
///     app.add_plugin(DefaultPlugins::new().title("Hello"));
///     app.add_system(Stage::Update, |ctx| {
///         let _dt = ctx.time().delta_secs();
///     });
/// }
///
/// space3d::main!(build);
/// ```
///
/// Requirements: the `platform` feature for Android; the crate depending on `space3d` needs
/// no `wasm-bindgen` dependency of its own (the macro uses the facade's re-export).
#[macro_export]
macro_rules! main {
    ($build:expr $(,)?) => {
        /// Entry point generated by `space3d::main!` (see the macro docs for per-platform behavior).
        pub fn main() {
            $crate::entry::main_entry($build);
        }

        #[cfg(target_arch = "wasm32")]
        #[$crate::__private::wasm_bindgen::prelude::wasm_bindgen(start, wasm_bindgen = $crate::__private::wasm_bindgen)]
        /// Web entry point generated by `space3d::main!`.
        pub fn __space3d_wasm_start() {
            $crate::entry::run_web($build);
        }

        #[cfg(target_os = "android")]
        #[unsafe(no_mangle)]
        /// Android entry point generated by `space3d::main!` (called by android-activity).
        fn android_main(android_app: $crate::__private::AndroidApp) {
            $crate::entry::run_android(android_app, $build);
        }

        #[cfg(target_os = "ios")]
        #[unsafe(no_mangle)]
        /// iOS entry point generated by `space3d::main!`; call it from `main.m`.
        pub extern "C" fn start_app() {
            $crate::entry::run_ios($build);
        }
    };
}
