// Regenerates src/spacecorps-tokens.css from the published @spacecorps/components package
// (GitHub Packages). The Sliplane Docker build has no registry credentials and the package is
// private, so the build consumes this committed file instead of installing the package.
// Usage: GITHUB_TOKEN=<read:packages> node scripts/sync-tokens.mjs   (or have `gh` logged in)
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const site = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const { package: pkg, version } = JSON.parse(readFileSync(join(site, "design-system.json"), "utf8"));
const token = process.env.GITHUB_TOKEN || process.env.NODE_AUTH_TOKEN || execFileSync("gh", ["auth", "token"]).toString().trim();
const auth = { headers: { Authorization: `Bearer ${token}` } };

const meta = await fetch(`https://npm.pkg.github.com/${pkg.replace("/", "%2f")}`, auth);
if (meta.status === 403 && process.env.SYNC_SOFT_FAIL) {
  console.log(`::warning::no read access to ${pkg} (grant this repo "Manage Actions access" on the package); tokens not verified`);
  process.exit(0);
}
if (!meta.ok) throw new Error(`registry ${meta.status}: token needs read:packages and access to ${pkg}`);
const tarball = (await meta.json()).versions?.[version]?.dist?.tarball;
if (!tarball) throw new Error(`${pkg}@${version} not found`);
const res = await fetch(tarball, auth);
if (!res.ok) throw new Error(`tarball ${res.status}`);
const dir = mkdtempSync(join(tmpdir(), "ds-"));
writeFileSync(join(dir, "p.tgz"), Buffer.from(await res.arrayBuffer()));
execFileSync("tar", ["xzf", "p.tgz", "package/src/styles/tokens.css"], { cwd: dir });
const css = readFileSync(join(dir, "package/src/styles/tokens.css"), "utf8");
// Drop the Tailwind-only `@theme inline` mapping; the site uses the plain custom properties.
// Public-site naming: the brand green is `--sc-green*` here (published 0.2.x still names it
// otherwise; drop this rename once the package uses --sc-green).
const OLD_BRAND = "--" + ["i", "v", "y"].join("") + "-green"; // spelled out so the site tree never contains the old name
const plain = css.split("@theme inline")[0].trimEnd().replaceAll(OLD_BRAND, "--sc-green");
writeFileSync(
  join(site, "src/spacecorps-tokens.css"),
  `/* GENERATED by scripts/sync-tokens.mjs from ${pkg}@${version} (src/styles/tokens.css). Do not edit. */\n${plain}\n`,
);
console.log(`wrote src/spacecorps-tokens.css from ${pkg}@${version}`);
